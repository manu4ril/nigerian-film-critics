alter table public.notifications enable row level security;

drop policy if exists "members read own notifications" on public.notifications;
create policy "members read own notifications"
on public.notifications for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "members mark own notifications read" on public.notifications;
create policy "members mark own notifications read"
on public.notifications for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create or replace function public.notify_application_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status
     and new.status in ('approved','rejected') then
    insert into public.notifications(user_id,title,body,type)
    values (
      new.user_id,
      case when new.status='approved' then 'Critic application approved' else 'Critic application update' end,
      case
        when new.status='approved' then 'Your application to become a verified Nigerian Film Critics contributor has been approved.'
        else 'Your critic application was not approved at this time. Check your account for the administrator note.'
      end,
      'application'
    );
  end if;
  return new;
end;
$$;

drop trigger if exists critic_application_notification on public.critic_applications;
create trigger critic_application_notification
after update of status on public.critic_applications
for each row execute function public.notify_application_status();

create or replace function public.notify_comment_approval()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  film_title text;
begin
  if new.approved = true and old.approved = false then
    select title into film_title from public.films where id = new.film_id;
    insert into public.notifications(user_id,title,body,type)
    values (
      new.user_id,
      'Comment approved',
      'Your comment on "' || coalesce(film_title,'a film review') || '" is now visible to readers.',
      'comment'
    );
  end if;
  return new;
end;
$$;

drop trigger if exists comment_approval_notification on public.comments;
create trigger comment_approval_notification
after update of approved on public.comments
for each row execute function public.notify_comment_approval();


-- Verified critic review submissions
create table if not exists public.critic_review_submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  critic_id bigint not null references public.critics(id) on delete cascade,
  title text not null,
  year int,
  genre text default '',
  category text default 'Nollywood',
  director text default '',
  poster_url text default '',
  score numeric(3,1),
  summary text default '',
  review text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  admin_notes text default '',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

alter table public.critic_review_submissions enable row level security;

drop policy if exists "critics submit own reviews" on public.critic_review_submissions;
create policy "critics submit own reviews"
on public.critic_review_submissions for insert
to authenticated
with check (
  user_id = auth.uid()
  and exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'critic'
  )
  and exists (
    select 1 from public.critics
    where id = critic_id and user_id = auth.uid()
  )
);

drop policy if exists "critics read own submissions" on public.critic_review_submissions;
create policy "critics read own submissions"
on public.critic_review_submissions for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "admins manage review submissions" on public.critic_review_submissions;
create policy "admins manage review submissions"
on public.critic_review_submissions for all
to authenticated
using (exists (select 1 from public.admins where user_id = auth.uid()))
with check (exists (select 1 from public.admins where user_id = auth.uid()));

create or replace function public.approve_critic_review_submission(
  submission_id bigint,
  admin_notes_value text default null
)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  s public.critic_review_submissions%rowtype;
  new_film_id bigint;
begin
  if not exists (select 1 from public.admins where user_id = auth.uid()) then
    raise exception 'Administrator access required';
  end if;

  select * into s from public.critic_review_submissions
  where id = submission_id for update;

  if not found then raise exception 'Review submission not found'; end if;
  if s.status <> 'pending' then raise exception 'This submission has already been reviewed'; end if;

  insert into public.films
    (title, year, genre, category, director, poster_url, critic_id, score, summary, review, published)
  values
    (s.title, s.year, s.genre, s.category, s.director, s.poster_url,
     s.critic_id, s.score, s.summary, s.review, true)
  returning id into new_film_id;

  update public.critic_review_submissions
  set status='approved', admin_notes=coalesce(admin_notes_value,''), reviewed_at=now()
  where id=s.id;

  insert into public.notifications(user_id,title,body,type)
  values (
    s.user_id,
    'Review published',
    'Your review of "' || s.title || '" has been approved and published on Nigerian Film Critics.',
    'review'
  );
end;
$$;

revoke all on function public.approve_critic_review_submission(bigint,text) from public;
grant execute on function public.approve_critic_review_submission(bigint,text) to authenticated;

create or replace function public.reject_critic_review_submission(
  submission_id bigint,
  admin_notes_value text default null
)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  s public.critic_review_submissions%rowtype;
begin
  if not exists (select 1 from public.admins where user_id = auth.uid()) then
    raise exception 'Administrator access required';
  end if;

  select * into s from public.critic_review_submissions
  where id = submission_id for update;

  if not found then raise exception 'Review submission not found'; end if;

  update public.critic_review_submissions
  set status='rejected', admin_notes=coalesce(admin_notes_value,''), reviewed_at=now()
  where id=s.id;

  insert into public.notifications(user_id,title,body,type)
  values (
    s.user_id,
    'Review submission update',
    'Your review of "' || s.title || '" was not approved for publication. Check your account for the administrator note.',
    'review'
  );
end;
$$;

revoke all on function public.reject_critic_review_submission(bigint,text) from public;
grant execute on function public.reject_critic_review_submission(bigint,text) to authenticated;
